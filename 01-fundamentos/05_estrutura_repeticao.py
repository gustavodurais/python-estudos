"""Estruturas de repetição: for com range e while."""

# range(10): de 0 até 9
for n in range(10):
    print(n)

# range(5, 16): de 5 até 15
for n in range(5, 16):
    print(n)

# range(10, 0, -1): contagem regressiva de 10 até 1
for n in range(10, 0, -1):
    print(n)

# while: repete enquanto a condição for verdadeira
x = 1
while x <= 15:
    print(x)
    x += 1
